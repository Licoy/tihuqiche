import QRCode from 'qrcode';
import { writeFile } from 'node:fs/promises';
import { shareUrl } from '../src/share.js';

const codes = {};
for (const locale of ['zh', 'en']) {
  codes[locale] = await QRCode.toString(shareUrl(locale), {
    type: 'svg', errorCorrectionLevel: 'M', margin: 4, width: 160,
    color: { dark: '#000000ff', light: '#ffffffff' },
  });
}
await writeFile(new URL('../src/share-qr.js', import.meta.url),
  `// Generated by pnpm share:qr; do not edit by hand.\nexport const SHARE_QR = Object.freeze(${JSON.stringify(codes, null, 2)});\n`);
